function getPumpkinPeteQuest(rawName) {
  if (!rawName || typeof rawName !== "string") return null;
  const trimmed = rawName.trim();
  if (PUMPKIN_PETE_QUESTS[trimmed]) {
    return PUMPKIN_PETE_QUESTS[trimmed];
  }
  const slug = trimmed.toLowerCase().replace(/['’]/g, "").replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "");
  if (PUMPKIN_PETE_QUESTS[slug]) {
    return PUMPKIN_PETE_QUESTS[slug];
  }
  const aliasKey = PUMPKIN_PETE_QUEST_ALIASES[slug] || PUMPKIN_PETE_QUEST_ALIASES[trimmed.toLowerCase()];
  if (aliasKey && PUMPKIN_PETE_QUESTS[aliasKey]) {
    return PUMPKIN_PETE_QUESTS[aliasKey];
  }
  const slugNoS = trimmed.toLowerCase().replace(/['’]s?\b/g, "").replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "");
  if (PUMPKIN_PETE_QUESTS[slugNoS]) {
    return PUMPKIN_PETE_QUESTS[slugNoS];
  }
  if (PUMPKIN_PETE_QUEST_ALIASES[slugNoS] && PUMPKIN_PETE_QUESTS[PUMPKIN_PETE_QUEST_ALIASES[slugNoS]]) {
    return PUMPKIN_PETE_QUESTS[PUMPKIN_PETE_QUEST_ALIASES[slugNoS]];
  }
  return null;
}
